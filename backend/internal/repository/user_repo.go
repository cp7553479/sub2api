// GetOrCreateSupabaseUser binds only the verified platform UUID. Deleted UUIDs
// remain reserved so a stale token can never revive their business history.
func (r *userBindingRepository) GetOrCreateSupabaseUser(ctx context.Context, userID uuid.UUID) (*service.User, error) {
	if userID == uuid.Nil {
		return nil, fmt.Errorf("platform user UUID is required")
	}
	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return nil, err
	}
	defer tx.Rollback()
	if _, err := tx.ExecContext(ctx, `SELECT pg_advisory_xact_lock(hashtextextended('sub2api-user:' || $1::text, 0))`, userID.String()); err != nil {
		return nil, err
	}
	var id int64
	err = tx.QueryRowContext(ctx, `
		INSERT INTO users (supabase_user_id, email)
		SELECT supabase_user_id, email FROM `+r.users.platformUsers+`
		WHERE supabase_user_id=$1 AND status='active'
		ON CONFLICT (supabase_user_id) DO UPDATE
		SET email = EXCLUDED.email, updated_at = NOW()
		WHERE users.deleted_at IS NULL
		RETURNING id
	`, userID).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, service.ErrUserNotFound
	}
	if err != nil {
		return nil, err
	}
	if err := tx.Commit(); err != nil {
		return nil, err
	}
	return r.users.GetByID(ctx, id)
}

